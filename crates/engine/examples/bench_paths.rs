//! Times the traversal and path-based measures, graph construction, and the
//! other per-node kernels on a few standard networks, and prints a
//! fingerprint of every result so that an optimization can be checked for
//! identical output.
//!
//!     cargo run --release --example bench_paths -- [filter] [--threads 1,2] [--runs 3]
//!
//! Each line gives the median wall time over `runs` repetitions, for each
//! thread count, and a 64-bit fingerprint of the result bits. Two builds
//! that print the same fingerprint computed bit-identical results. On
//! Linux the single-thread column also gives the process CPU time
//! (`cpu=`), which is steadier than wall time on a loaded machine.
//!
//! The networks are generated by `knappnet::generate` with fixed seeds:
//!
//! | Name | Nodes | Edges | Kind |
//! |---|---|---|---|
//! | `sparse10k` | 10 000 | 50 000 | G(n, m), undirected |
//! | `dir10k` | 10 000 | 50 000 | G(n, m), directed |
//! | `dense2k` | 2 000 | 200 000 | G(n, m), undirected |
//! | `sparse100k` | 100 000 | 500 000 | G(n, m), undirected |
//! | `pa100k` | 100 000 | 499 990 | preferential attachment, m = 5 |
//!
//! Weighted variants carry integer weights 1..8 (`int`) or real weights in
//! (0.5, 4) (`real`). All-pairs measures run on the 10k and 2k networks
//! only; linear-time measures run on every network.

use std::time::Instant;

use knappnet::generate;
use knappnet::metrics::betweenness::{betweenness, BetweennessOptions};
use knappnet::metrics::brokerage::{constraint, effective_size, StructuralHoleOptions};
use knappnet::metrics::closeness::{closeness, harmonic_centrality, ClosenessOptions};
use knappnet::metrics::cores::coreness;
use knappnet::metrics::degree::{degree, strength, DegreeMode};
use knappnet::metrics::descriptive::{
    average_clustering, distances, eccentricity, local_clustering, path_summary, reachability,
    transitivity, triangles, ClusteringOptions, PathOptions, Weighting,
};
use knappnet::metrics::ego::{ego_summary, neighborhood_sizes, EgoOptions, NeighborhoodOptions};
use knappnet::metrics::eigenvector::{eigenvector_centrality, EigenvectorOptions};
use knappnet::metrics::mixing::{assortativity_degree, AssortOptions};
use knappnet::metrics::reach::{edge_betweenness, reach, EdgeBetweennessOptions, ReachOptions};
use knappnet::metrics::spectral::{hits, katz, pagerank, HitsOptions, KatzOptions, PagerankOptions};
use knappnet::metrics::triad::triad_census;
use knappnet::rng::Stream;
use knappnet::{Graph, PathAlgorithm};

struct Net {
    name: &'static str,
    n: usize,
    from: Vec<i64>,
    to: Vec<i64>,
    directed: bool,
    int_weights: Vec<f64>,
    real_weights: Vec<f64>,
}

impl Net {
    fn build(name: &'static str, list: generate::EdgeList, seed: u64) -> Net {
        let mut rng = Stream::new(seed, 0);
        let m = list.len();
        let int_weights = (0..m).map(|_| 1.0 + rng.below(8) as f64).collect();
        let real_weights = (0..m).map(|_| 0.5 + 3.5 * rng.uniform()).collect();
        Net {
            name,
            n: list.n,
            from: list.from.iter().map(|&v| v as i64).collect(),
            to: list.to.iter().map(|&v| v as i64).collect(),
            directed: list.directed,
            int_weights,
            real_weights,
        }
    }

    fn graph(&self, weights: Option<&[f64]>) -> Graph {
        Graph::from_edges(self.n, &self.from, &self.to, weights, self.directed).unwrap()
    }
}

/// Process CPU time in seconds (user plus system), from `/proc/self/stat`
/// on Linux; `None` elsewhere.
fn cpu_seconds() -> Option<f64> {
    let stat = std::fs::read_to_string("/proc/self/stat").ok()?;
    // Fields after the parenthesized command name; utime and stime are
    // the 14th and 15th fields of the line, in clock ticks.
    let rest = &stat[stat.rfind(')')? + 2..];
    let fields: Vec<&str> = rest.split_whitespace().collect();
    let utime: f64 = fields.get(11)?.parse().ok()?;
    let stime: f64 = fields.get(12)?.parse().ok()?;
    Some((utime + stime) / 100.0)
}

/// FNV-1a over the bit patterns of the values.
fn fingerprint(values: &[f64]) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for v in values {
        for b in v.to_bits().to_le_bytes() {
            h ^= b as u64;
            h = h.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    h
}

struct Bench {
    filter: Option<String>,
    threads: Vec<usize>,
    runs: usize,
}

impl Bench {
    fn time<F: FnMut(usize) -> Vec<f64>>(&self, label: &str, mut f: F) {
        if let Some(filter) = &self.filter {
            if !label.contains(filter.as_str()) {
                return;
            }
        }
        let mut line = format!("{label:<46}");
        let mut prints = Vec::new();
        for &t in &self.threads {
            let mut times = Vec::with_capacity(self.runs);
            let mut cpu = Vec::with_capacity(self.runs);
            let mut print = 0;
            for _ in 0..self.runs {
                let cpu_start = cpu_seconds();
                let start = Instant::now();
                let out = f(t);
                times.push(start.elapsed().as_secs_f64());
                if let (Some(a), Some(b)) = (cpu_start, cpu_seconds()) {
                    cpu.push(b - a);
                }
                print = fingerprint(&out);
            }
            times.sort_by(|a, b| a.partial_cmp(b).unwrap());
            cpu.sort_by(|a, b| a.partial_cmp(b).unwrap());
            let median = times[times.len() / 2];
            line.push_str(&format!(" t={t}:{median:>9.4}s"));
            if t == 1 && !cpu.is_empty() {
                line.push_str(&format!(" cpu={:>9.4}s", cpu[cpu.len() / 2]));
            }
            prints.push(print);
        }
        line.push_str(&format!("  {:016x}", prints[0]));
        if prints.iter().any(|&p| p != prints[0]) {
            line.push_str("  (differs across thread counts)");
        }
        println!("{line}");
    }
}

fn main() {
    let mut args = std::env::args().skip(1);
    let mut bench = Bench {
        filter: None,
        threads: vec![1, 2],
        runs: 3,
    };
    while let Some(a) = args.next() {
        match a.as_str() {
            "--threads" => {
                bench.threads = args
                    .next()
                    .expect("thread list")
                    .split(',')
                    .map(|s| s.parse().expect("thread count"))
                    .collect();
            }
            "--runs" => bench.runs = args.next().expect("run count").parse().expect("runs"),
            other => bench.filter = Some(other.to_string()),
        }
    }

    let nets = vec![
        Net::build(
            "sparse10k",
            generate::gnm(10_000, 50_000, false, false, 1, 1, 1)
                .unwrap()
                .remove(0),
            11,
        ),
        Net::build(
            "dir10k",
            generate::gnm(10_000, 50_000, true, false, 1, 2, 1)
                .unwrap()
                .remove(0),
            12,
        ),
        Net::build(
            "dense2k",
            generate::gnm(2_000, 200_000, false, false, 1, 3, 1)
                .unwrap()
                .remove(0),
            13,
        ),
        Net::build(
            "sparse100k",
            generate::gnm(100_000, 500_000, false, false, 1, 4, 1)
                .unwrap()
                .remove(0),
            14,
        ),
        Net::build(
            "pa100k",
            generate::preferential(100_000, 5, 1, 5, 1).unwrap().remove(0),
            15,
        ),
    ];

    for net in &nets {
        let name = net.name;
        let all_pairs = net.n <= 10_000;
        let g = net.graph(None);
        let gi = net.graph(Some(&net.int_weights));
        let gr = net.graph(Some(&net.real_weights));
        println!(
            "== {name}: n = {}, m = {}, {}",
            g.node_count(),
            g.edge_count(),
            if g.is_directed() {
                "directed"
            } else {
                "undirected"
            }
        );

        bench.time(&format!("{name} graph_from_edges"), |_| {
            let h = net.graph(None);
            vec![h.out().arc_count() as f64]
        });
        bench.time(&format!("{name} simple_undirected"), |_| {
            let s = g.simple_undirected(false);
            vec![s.arc_count() as f64]
        });

        if all_pairs {
            for (tag, h, weighted, algorithm) in [
                ("bfs", &g, false, PathAlgorithm::Auto),
                ("dial", &gi, true, PathAlgorithm::Auto),
                ("dijkstra", &gr, true, PathAlgorithm::Auto),
            ] {
                bench.time(&format!("{name} betweenness {tag}"), |t| {
                    betweenness(
                        h,
                        BetweennessOptions {
                            weighted,
                            algorithm,
                            threads: t,
                            ..Default::default()
                        },
                    )
                    .unwrap()
                });
                bench.time(&format!("{name} closeness {tag}"), |t| {
                    closeness(
                        h,
                        ClosenessOptions {
                            weighted,
                            algorithm,
                            threads: t,
                            ..Default::default()
                        },
                    )
                    .unwrap()
                });
                bench.time(&format!("{name} harmonic {tag}"), |t| {
                    harmonic_centrality(
                        h,
                        ClosenessOptions {
                            weighted,
                            algorithm,
                            threads: t,
                            ..Default::default()
                        },
                    )
                    .unwrap()
                });
                bench.time(&format!("{name} eccentricity {tag}"), |t| {
                    eccentricity(
                        h,
                        PathOptions {
                            weighted,
                            algorithm,
                            threads: t,
                            ..Default::default()
                        },
                    )
                    .unwrap()
                });
                bench.time(&format!("{name} path_summary {tag}"), |t| {
                    let s = path_summary(
                        h,
                        None,
                        PathOptions {
                            weighted,
                            algorithm,
                            threads: t,
                            ..Default::default()
                        },
                    )
                    .unwrap();
                    vec![s.pairs as f64, s.total, s.longest, s.incomplete as f64]
                });
                bench.time(&format!("{name} edge_betweenness {tag}"), |t| {
                    edge_betweenness(
                        h,
                        EdgeBetweennessOptions {
                            weighted,
                            algorithm,
                            threads: t,
                            ..Default::default()
                        },
                    )
                    .unwrap()
                });
            }
            let sources: Vec<u32> = (0..500).collect();
            bench.time(&format!("{name} distances 500 sources bfs"), |t| {
                distances(
                    &g,
                    Some(&sources),
                    PathOptions {
                        threads: t,
                        ..Default::default()
                    },
                )
                .unwrap()
                .as_slice()
                .to_vec()
            });
            if g.is_directed() {
                bench.time(&format!("{name} reachability out"), |t| {
                    reachability(&g, DegreeMode::Out, t).unwrap()
                });
            }
            bench.time(&format!("{name} reach k=2"), |t| {
                reach(
                    &g,
                    ReachOptions {
                        threads: t,
                        ..Default::default()
                    },
                )
                .unwrap()
            });
            bench.time(&format!("{name} reach k=3 weighted int"), |t| {
                reach(
                    &gi,
                    ReachOptions {
                        k: 3.0,
                        weighted: true,
                        threads: t,
                        ..Default::default()
                    },
                )
                .unwrap()
            });
            bench.time(&format!("{name} ego_summary order 1"), |t| {
                let e = ego_summary(
                    &g,
                    EgoOptions {
                        threads: t,
                        ..Default::default()
                    },
                )
                .unwrap();
                let mut out = e.density;
                out.extend(e.betweenness.unwrap_or_default());
                out
            });
        }

        bench.time(&format!("{name} triangles"), |t| {
            triangles(&g, t).into_iter().map(|x| x as f64).collect()
        });
        bench.time(&format!("{name} local_clustering"), |t| {
            local_clustering(
                &g,
                ClusteringOptions {
                    threads: t,
                    ..Default::default()
                },
            )
            .unwrap()
        });
        bench.time(&format!("{name} local_clustering barrat"), |t| {
            local_clustering(
                &gr,
                ClusteringOptions {
                    weighting: Weighting::Barrat,
                    threads: t,
                    ..Default::default()
                },
            )
            .unwrap()
        });
        bench.time(&format!("{name} transitivity"), |t| {
            vec![transitivity(
                &g,
                ClusteringOptions {
                    threads: t,
                    ..Default::default()
                },
            )]
        });
        bench.time(&format!("{name} average_clustering"), |t| {
            vec![average_clustering(
                &g,
                ClusteringOptions {
                    threads: t,
                    ..Default::default()
                },
            )
            .unwrap()]
        });
        bench.time(&format!("{name} coreness"), |_| {
            coreness(&g, DegreeMode::All)
                .into_iter()
                .map(|x| x as f64)
                .collect()
        });
        bench.time(&format!("{name} triad_census"), |t| {
            triad_census(&g, t).to_vec()
        });
        bench.time(&format!("{name} degree"), |_| {
            degree(&g, DegreeMode::All, true)
        });
        bench.time(&format!("{name} strength"), |_| {
            strength(&gr, DegreeMode::All, true).unwrap()
        });
        bench.time(&format!("{name} pagerank"), |t| {
            pagerank(
                &g,
                &PagerankOptions {
                    threads: t,
                    ..Default::default()
                },
            )
            .unwrap()
        });
        bench.time(&format!("{name} pagerank weighted"), |t| {
            pagerank(
                &gr,
                &PagerankOptions {
                    weighted: true,
                    threads: t,
                    ..Default::default()
                },
            )
            .unwrap()
        });
        bench.time(&format!("{name} eigenvector"), |t| {
            eigenvector_centrality(
                &g,
                EigenvectorOptions {
                    threads: t,
                    ..Default::default()
                },
            )
            .unwrap()
            .values
        });
        bench.time(&format!("{name} katz"), |t| {
            katz(
                &g,
                &KatzOptions {
                    alpha: 0.01,
                    threads: t,
                    ..Default::default()
                },
            )
            .unwrap()
        });
        bench.time(&format!("{name} hits"), |t| {
            let h = hits(
                &g,
                HitsOptions {
                    threads: t,
                    ..Default::default()
                },
            )
            .unwrap();
            let mut out = h.hubs;
            out.extend(h.authorities);
            out
        });
        bench.time(&format!("{name} constraint"), |t| {
            constraint(
                &g,
                StructuralHoleOptions {
                    weighted: false,
                    threads: t,
                },
            )
            .unwrap()
        });
        bench.time(&format!("{name} effective_size"), |t| {
            effective_size(
                &g,
                StructuralHoleOptions {
                    weighted: false,
                    threads: t,
                },
            )
            .unwrap()
        });
        bench.time(&format!("{name} assortativity_degree"), |_| {
            vec![assortativity_degree(
                &g,
                false,
                AssortOptions {
                    directed: true,
                    ..Default::default()
                },
            )
            .unwrap()]
        });
        bench.time(&format!("{name} neighborhood_sizes order 2"), |t| {
            neighborhood_sizes(
                &g,
                None,
                NeighborhoodOptions {
                    order: 2,
                    threads: t,
                    ..Default::default()
                },
            )
            .unwrap()
            .into_iter()
            .map(|x| x as f64)
            .collect()
        });
    }
}

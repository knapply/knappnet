/// One measure on one network at one thread count.
struct Record {
    net: String,
    class: &'static str,
    n: usize,
    m: usize,
    directed: bool,
    measure: &'static str,
    cost: Cost,
    threads: usize,
    wall: f64,
    cpu: Option<f64>,
    heap: usize,
    allocs: usize,
    rss_kb: Option<u64>,
    print: u64,
    phases: Vec<(&'static str, f64)>,
}

struct Bench {
    filter: Option<String>,
    threads: Vec<usize>,
    runs: usize,
    phases: bool,
    records: Vec<Record>,
    rss_resettable: bool,
}

impl Bench {
    fn wanted(&self, label: &str) -> bool {
        self.filter
            .as_ref()
            .map_or(true, |f| label.contains(f.as_str()))
    }

    fn time(&mut self, x: &Graphs, m: &Measure) {
        let label = format!("{} {}", x.net.name, m.name);
        if !self.wanted(&label) {
            return;
        }
        let mut line = format!("{label:<44}");
        let mut first: Option<(f64, u64)> = None;
        for &t in &self.threads.clone() {
            let mut times = Vec::with_capacity(self.runs);
            let mut cpu = Vec::with_capacity(self.runs);
            let (mut print, mut heap, mut allocs) = (0, 0, 0);
            let mut phases = Vec::new();
            self.rss_resettable = reset_peak_rss();
            for run in 0..self.runs {
                probe::enable(self.phases && run + 1 == self.runs);
                probe::take();
                let cpu_start = cpu_seconds();
                let start = Instant::now();
                let (out, h, a) = heap_probe(|| (m.run)(x, t));
                times.push(start.elapsed().as_secs_f64());
                if let (Some(a), Some(b)) = (cpu_start, cpu_seconds()) {
                    cpu.push(b - a);
                }
                probe::enable(false);
                phases = probe::take();
                print = fingerprint(&out);
                heap = h;
                allocs = a;
            }
            let rss_kb = peak_rss_kb();
            times.sort_by(|a, b| a.total_cmp(b));
            cpu.sort_by(|a, b| a.total_cmp(b));
            let wall = times[times.len() / 2];
            let cpu = cpu.get(cpu.len() / 2).copied();
            let _ = write!(line, " t={t}:{wall:>8.4}s");
            match first {
                None => {
                    if let Some(c) = cpu {
                        let _ = write!(line, " cpu={c:>8.4}s");
                    }
                    let _ = write!(line, " heap={} allocs={allocs}", bytes(heap));
                    first = Some((wall, print));
                }
                Some((w1, p1)) => {
                    let _ = write!(line, " (x{:.2})", w1 / wall);
                    if p1 != print {
                        line.push_str(" [differs]");
                    }
                }
            }
            self.records.push(Record {
                net: x.net.name.clone(),
                class: x.net.class,
                n: x.g.node_count(),
                m: x.g.edge_count(),
                directed: x.g.is_directed(),
                measure: m.name,
                cost: m.cost,
                threads: t,
                wall,
                cpu,
                heap,
                allocs,
                rss_kb,
                print,
                phases: phases.clone(),
            });
            if !phases.is_empty() && t == self.threads[0] {
                let total: f64 = phases.iter().map(|p| p.1).sum();
                let mut s = String::from("    phases:");
                for (name, secs) in &phases {
                    let _ = write!(s, " {name}={secs:.4}s ({:.0}%)", 100.0 * secs / total);
                }
                println!("{line}");
                line = s;
            }
        }
        let _ = write!(line, "  {:016x}", first.map_or(0, |f| f.1));
        println!("{line}");
    }
}

fn bytes(b: usize) -> String {
    if b >= 1 << 30 {
        format!("{:.2}G", b as f64 / (1u64 << 30) as f64)
    } else if b >= 1 << 20 {
        format!("{:.1}M", b as f64 / (1u64 << 20) as f64)
    } else if b >= 1 << 10 {
        format!("{:.1}K", b as f64 / 1024.0)
    } else {
        format!("{b}B")
    }
}

/// Whether a measure runs on a network: all-pairs measures only up to
/// `all_pairs_max` nodes, directed-only measures only on directed networks.
fn applies(m: &Measure, x: &Graphs, all_pairs_max: usize) -> bool {
    if m.name == "reachability out" && !x.g.is_directed() {
        return false;
    }
    m.cost != Cost::AllPairs || x.g.node_count() <= all_pairs_max
}

fn run_network(bench: &mut Bench, net: &Net, all_pairs_max: usize) {
    if !MEASURES
        .iter()
        .any(|m| bench.wanted(&format!("{} {}", net.name, m.name)))
    {
        return;
    }
    let x = Graphs {
        net,
        g: net.graph(None),
        gi: net.graph(Some(&net.int_weights)),
        gr: net.graph(Some(&net.real_weights)),
    };
    println!(
        "== {}: {}, n = {}, m = {}, density {:.4}, {}",
        net.name,
        net.class,
        x.g.node_count(),
        x.g.edge_count(),
        density(x.g.node_count(), x.g.edge_count(), x.g.is_directed()),
        if x.g.is_directed() {
            "directed"
        } else {
            "undirected"
        }
    );
    for m in MEASURES {
        if applies(m, &x, all_pairs_max) {
            bench.time(&x, m);
        }
    }
}

fn density(n: usize, m: usize, directed: bool) -> f64 {
    let pairs = (n * n.saturating_sub(1)) as f64;
    m as f64 / if directed { pairs } else { pairs / 2.0 }
}

// ---- Complexity fits -------------------------------------------------------

/// Least-squares slope of log y on log x; `None` with fewer than three
/// usable points.
fn loglog_slope(points: &[(f64, f64)]) -> Option<f64> {
    let p: Vec<(f64, f64)> = points
        .iter()
        .filter(|&&(x, y)| x > 0.0 && y > 0.0)
        .map(|&(x, y)| (x.ln(), y.ln()))
        .collect();
    if p.len() < 3 {
        return None;
    }
    let k = p.len() as f64;
    let mx = p.iter().map(|q| q.0).sum::<f64>() / k;
    let my = p.iter().map(|q| q.1).sum::<f64>() / k;
    let sxy: f64 = p.iter().map(|q| (q.0 - mx) * (q.1 - my)).sum();
    let sxx: f64 = p.iter().map(|q| (q.0 - mx) * (q.0 - mx)).sum();
    Some(sxy / sxx)
}

struct Fit {
    measure: &'static str,
    ladder: &'static str,
    cost: Cost,
    time_slope: Option<f64>,
    heap_slope: Option<f64>,
    expected: f64,
    points: usize,
}

/// Fits slopes per measure on the records of one ladder, using single
/// thread timings; times under 2 ms are too noisy to fit and are dropped.
fn fit(records: &[Record], ladder: &'static str, threads: usize) -> Vec<Fit> {
    let mut out = Vec::new();
    for m in MEASURES {
        let rows: Vec<&Record> = records
            .iter()
            .filter(|r| r.measure == m.name && r.class == ladder && r.threads == threads)
            .collect();
        let x = |r: &Record| if ladder == "ladder-n" { r.n } else { r.m } as f64;
        let time: Vec<(f64, f64)> = rows
            .iter()
            .filter(|r| r.wall >= 0.002)
            .map(|r| (x(r), r.cpu.filter(|&c| c >= 0.05).unwrap_or(r.wall)))
            .collect();
        let heap: Vec<(f64, f64)> = rows.iter().map(|r| (x(r), r.heap as f64)).collect();
        let (en, em) = m.cost.expected();
        out.push(Fit {
            measure: m.name,
            ladder,
            cost: m.cost,
            time_slope: loglog_slope(&time),
            heap_slope: loglog_slope(&heap),
            expected: if ladder == "ladder-n" { en } else { em },
            points: time.len(),
        });
    }
    out
}

// ---- Output ----------------------------------------------------------------

fn write_csv(path: &str, records: &[Record]) {
    let mut s = String::from(
        "network,class,n,m,directed,measure,cost,threads,wall_s,cpu_s,peak_heap_bytes,\
         allocations,heap_bytes_per_node,heap_bytes_per_edge,peak_rss_kb,fingerprint,phases\n",
    );
    for r in records {
        let phases: Vec<String> = r
            .phases
            .iter()
            .map(|(k, v)| format!("{k}={v:.6}"))
            .collect();
        let _ = writeln!(
            s,
            "{},{},{},{},{},{},{},{},{:.6},{},{},{},{:.2},{:.2},{},{:016x},{}",
            r.net,
            r.class,
            r.n,
            r.m,
            r.directed,
            r.measure,
            r.cost.label(),
            r.threads,
            r.wall,
            r.cpu.map_or(String::new(), |c| format!("{c:.3}")),
            r.heap,
            r.allocs,
            r.heap as f64 / r.n.max(1) as f64,
            r.heap as f64 / r.m.max(1) as f64,
            r.rss_kb.map_or(String::new(), |k| k.to_string()),
            r.print,
            phases.join(";")
        );
    }
    std::fs::write(path, s).expect("write csv");
}

fn summarize(bench: &Bench, fits: &[Fit]) -> String {
    let cores = std::thread::available_parallelism().map_or(1, |n| n.get());
    let t0 = bench.threads[0];
    let mut s = String::new();
    let _ = writeln!(s, "# Benchmark summary\n");
    let _ = writeln!(
        s,
        "{cores} cores available; threads timed: {:?}; {} run(s) per point; \
         peak RSS reset per measure: {}.\n",
        bench.threads, bench.runs, bench.rss_resettable
    );
    let base: Vec<&Record> = bench.records.iter().filter(|r| r.threads == t0).collect();

    let mut by_time = base.clone();
    by_time.sort_by(|a, b| b.wall.total_cmp(&a.wall));
    let _ = writeln!(s, "## Largest single-thread costs\n");
    let _ = writeln!(
        s,
        "| Network | Measure | Time (s) | CPU (s) | Peak heap | Bytes/edge | Allocations |"
    );
    let _ = writeln!(s, "|---|---|---|---|---|---|---|");
    for r in by_time.iter().take(15) {
        let _ = writeln!(
            s,
            "| {} | {} | {:.3} | {} | {} | {:.1} | {} |",
            r.net,
            r.measure,
            r.wall,
            r.cpu.map_or("".into(), |c| format!("{c:.2}")),
            bytes(r.heap),
            r.heap as f64 / r.m.max(1) as f64,
            r.allocs
        );
    }

    let mut by_alloc = base.clone();
    by_alloc.retain(|r| r.allocs as f64 > 4.0 * r.n as f64);
    by_alloc.sort_by_key(|r| std::cmp::Reverse(r.allocs / r.n.max(1)));
    if !by_alloc.is_empty() {
        let _ = writeln!(
            s,
            "\n## Allocation-heavy measures (more than 4 allocations per node)\n"
        );
        let _ = writeln!(s, "| Network | Measure | Allocations | Per node |");
        let _ = writeln!(s, "|---|---|---|---|");
        for r in by_alloc.iter().take(15) {
            let _ = writeln!(
                s,
                "| {} | {} | {} | {:.1} |",
                r.net,
                r.measure,
                r.allocs,
                r.allocs as f64 / r.n as f64
            );
        }
    }

    let mut by_mem = base.clone();
    by_mem.retain(|r| r.heap as f64 > 64.0 * (r.n + r.m) as f64);
    by_mem.sort_by_key(|r| std::cmp::Reverse(r.heap));
    if !by_mem.is_empty() {
        let _ = writeln!(
            s,
            "\n## Memory-heavy measures (peak heap above 64 bytes per node plus edge)\n"
        );
        let _ = writeln!(s, "| Network | Measure | Peak heap | Bytes per (n + m) |");
        let _ = writeln!(s, "|---|---|---|---|");
        for r in by_mem.iter().take(15) {
            let _ = writeln!(
                s,
                "| {} | {} | {} | {:.0} |",
                r.net,
                r.measure,
                bytes(r.heap),
                r.heap as f64 / (r.n + r.m) as f64
            );
        }
    }

    if bench.threads.len() > 1 {
        let _ = writeln!(s, "\n## Thread scaling (measures over 50 ms)\n");
        let _ = write!(s, "| Network | Measure | t={t0} (s) |");
        for t in &bench.threads[1..] {
            let _ = write!(s, " speedup t={t} | efficiency t={t} |");
        }
        let _ = writeln!(s, " Same bits |");
        let _ = writeln!(
            s,
            "|---|---|---|{}---|",
            "---|---|".repeat(bench.threads.len() - 1)
        );
        for r in base.iter().filter(|r| r.wall >= 0.05) {
            let _ = write!(s, "| {} | {} | {:.3} |", r.net, r.measure, r.wall);
            let mut same = true;
            for &t in &bench.threads[1..] {
                if let Some(q) = bench
                    .records
                    .iter()
                    .find(|q| q.threads == t && q.net == r.net && q.measure == r.measure)
                {
                    let sp = r.wall / q.wall;
                    let eff = sp * t0 as f64 / t as f64;
                    let _ = write!(s, " {sp:.2} | {:.0}% |", 100.0 * eff);
                    same &= q.print == r.print;
                } else {
                    s.push_str(" | |");
                }
            }
            let _ = writeln!(s, " {} |", if same { "yes" } else { "no" });
        }
    }

    let phased: Vec<&&Record> = base.iter().filter(|r| !r.phases.is_empty()).collect();
    if !phased.is_empty() {
        let _ = writeln!(s, "\n## Phases inside instrumented measures\n");
        let _ = writeln!(s, "| Network | Measure | Phases (share of time) |");
        let _ = writeln!(s, "|---|---|---|");
        for r in phased {
            let total: f64 = r.phases.iter().map(|p| p.1).sum();
            let parts: Vec<String> = r
                .phases
                .iter()
                .map(|(k, v)| format!("{k} {:.0}%", 100.0 * v / total))
                .collect();
            let _ = writeln!(s, "| {} | {} | {} |", r.net, r.measure, parts.join(", "));
        }
    }

    if !fits.is_empty() {
        let _ = writeln!(s, "\n## Empirical complexity\n");
        let _ = writeln!(
            s,
            "Slopes of log time and log peak heap against log n (`ladder-n`, average degree 10) \
             or log m (`ladder-m`, n = 2000). Flagged when the time slope exceeds the expected \
             exponent by more than 0.25.\n"
        );
        let _ = writeln!(
            s,
            "| Measure | Ladder | Expected | Time slope | Heap slope | Points | Flag |"
        );
        let _ = writeln!(s, "|---|---|---|---|---|---|---|");
        for f in fits {
            let flag = match f.time_slope {
                Some(t) if t > f.expected + 0.25 => "**above**",
                _ => "",
            };
            let _ = writeln!(
                s,
                "| {} | {} | {} ({:.1}) | {} | {} | {} | {} |",
                f.measure,
                f.ladder,
                f.cost.label(),
                f.expected,
                f.time_slope.map_or("-".into(), |v| format!("{v:.2}")),
                f.heap_slope.map_or("-".into(), |v| format!("{v:.2}")),
                f.points,
                flag
            );
        }
    }
    s
}

// ---- Main ------------------------------------------------------------------

fn main() {
    let mut args = std::env::args().skip(1);
    let mut bench = Bench {
        filter: None,
        threads: vec![1, 2],
        runs: 3,
        phases: false,
        records: Vec::new(),
        rss_resettable: false,
    };
    let (mut ladder, mut csv, mut summary_path) = (false, None, None);
    while let Some(a) = args.next() {
        match a.as_str() {
            "--threads" => {
                bench.threads = args
                    .next()
                    .expect("thread list")
                    .split(',')
                    .map(|s| s.parse().expect("thread count"))
                    .collect();
            }
            "--runs" => bench.runs = args.next().expect("run count").parse().expect("runs"),
            "--ladder" => ladder = true,
            "--phases" => bench.phases = true,
            "--csv" => csv = Some(args.next().expect("csv path")),
            "--summary" => summary_path = Some(args.next().expect("summary path")),
            other => bench.filter = Some(other.to_string()),
        }
    }
    println!(
        "{} cores available; threads {:?}; {} run(s)",
        std::thread::available_parallelism().map_or(1, |n| n.get()),
        bench.threads,
        bench.runs
    );

    let mut fits = Vec::new();
    if ladder {
        let mut seed = 100;
        let mut n = 1000;
        while n <= 256_000 {
            seed += 1;
            let net = Net::gnm(
                &format!("n{}k", n / 1000),
                "ladder-n",
                n,
                5 * n as u64,
                false,
                seed,
            );
            run_network(&mut bench, &net, 16_000);
            n *= 2;
        }
        for pct in [0.5, 1.0, 2.0, 5.0, 10.0, 20.0, 40.0] {
            seed += 1;
            let n = 2000usize;
            let m = (pct / 100.0 * (n * (n - 1) / 2) as f64) as u64;
            let net = Net::gnm(&format!("d{pct}%"), "ladder-m", n, m, false, seed);
            run_network(&mut bench, &net, n);
        }
        fits.extend(fit(&bench.records, "ladder-n", bench.threads[0]));
        fits.extend(fit(&bench.records, "ladder-m", bench.threads[0]));
    } else {
        let nets = [
            Net::gnm("sparse10k", "sparse", 10_000, 50_000, false, 1),
            Net::gnm("dir10k", "sparse", 10_000, 50_000, true, 2),
            Net::gnm("medium3k", "medium", 3_000, 89_970, false, 6),
            Net::gnm("meddir3k", "medium", 3_000, 179_940, true, 7),
            Net::gnm("dense2k", "dense", 2_000, 200_000, false, 3),
            Net::gnm("dense1k", "dense", 1_000, 149_850, false, 8),
            Net::gnm("densedir1k", "dense", 1_000, 299_700, true, 9),
            Net::gnm("sparse100k", "sparse", 100_000, 500_000, false, 4),
            Net::build(
                "pa100k".to_string(),
                "sparse",
                generate::preferential(100_000, 5, 1, 5, 1)
                    .unwrap()
                    .remove(0),
                15,
            ),
        ];
        for net in &nets {
            run_network(&mut bench, net, 10_000);
        }
    }

    if let Some(path) = csv {
        write_csv(&path, &bench.records);
    }
    let text = summarize(&bench, &fits);
    match summary_path {
        Some(path) => std::fs::write(path, text).expect("write summary"),
        None if ladder => println!("\n{text}"),
        None => {}
    }
}

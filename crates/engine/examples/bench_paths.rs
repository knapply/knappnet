struct Net {
    name: String,
    class: &'static str,
    n: usize,
    from: Vec<i64>,
    to: Vec<i64>,
    directed: bool,
    int_weights: Vec<f64>,
    real_weights: Vec<f64>,
}

impl Net {
    fn build(name: String, class: &'static str, list: generate::EdgeList, seed: u64) -> Net {
        let mut rng = Stream::new(seed, 0);
        let m = list.len();
        let int_weights = (0..m).map(|_| 1.0 + rng.below(8) as f64).collect();
        let real_weights = (0..m).map(|_| 0.5 + 3.5 * rng.uniform()).collect();
        Net {
            name,
            class,
            n: list.n,
            from: list.from.iter().map(|&v| v as i64).collect(),
            to: list.to.iter().map(|&v| v as i64).collect(),
            directed: list.directed,
            int_weights,
            real_weights,
        }
    }

    fn gnm(name: &str, class: &'static str, n: usize, m: u64, directed: bool, seed: u64) -> Net {
        let list = generate::gnm(n, m, directed, false, 1, seed, 1)
            .unwrap()
            .remove(0);
        Net::build(name.to_string(), class, list, seed + 10)
    }

    fn graph(&self, weights: Option<&[f64]>) -> Graph {
        Graph::from_edges(self.n, &self.from, &self.to, weights, self.directed).unwrap()
    }
}

/// The network in its unweighted, integer-weighted, and real-weighted
/// forms.
struct Graphs<'a> {
    net: &'a Net,
    g: Graph,
    gi: Graph,
    gr: Graph,
}

/// How the cost of a measure is expected to grow: the exponent of n on the
/// sparse ladder (average degree fixed, so m grows like n) and of m on the
/// dense ladder (n fixed).
#[derive(Clone, Copy, PartialEq)]
enum Cost {
    /// O(n + m): one pass, or a fixed number of passes, over the arcs.
    Linear,
    /// O(n + m) per iteration with an iteration count that does not grow
    /// with the network (power iteration).
    Iterative,
    /// O(nm) (one search per node), O(nm + n^2 log n) with a heap.
    AllPairs,
    /// O(sum of squared degrees): wedge enumeration (triangles, triads,
    /// structural holes). Linear on the sparse ladder, quadratic in m at
    /// fixed n.
    Wedges,
    /// O(sum of cubed degrees): a search inside every ego network.
    EgoSearch,
}

impl Cost {
    fn expected(self) -> (f64, f64) {
        match self {
            Cost::Linear | Cost::Iterative => (1.0, 1.0),
            Cost::AllPairs => (2.0, 1.0),
            Cost::Wedges => (1.0, 2.0),
            Cost::EgoSearch => (1.0, 3.0),
        }
    }

    fn label(self) -> &'static str {
        match self {
            Cost::Linear => "O(n+m)",
            Cost::Iterative => "O(k(n+m))",
            Cost::AllPairs => "O(nm)",
            Cost::Wedges => "O(sum d^2)",
            Cost::EgoSearch => "O(sum d^3)",
        }
    }
}


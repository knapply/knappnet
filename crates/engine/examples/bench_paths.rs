//! Times the traversal and path-based measures, graph construction, and the
//! other per-node kernels, and reports what is needed to decide what to
//! optimize: wall and CPU time, heap use and allocation counts, peak
//! resident memory, thread scaling, empirical complexity, and the time of
//! each phase inside the expensive measures. It prints a fingerprint of
//! every result so that an optimization can be checked for identical
//! output.
//!
//!     cargo run --release --example bench_paths -- [filter] [options]
//!
//! Options:
//!
//! - `--threads 1,2,4`: thread counts to time (default `1,2`). Speedup and
//!   parallel efficiency are reported against the first count.
//! - `--runs 3`: repetitions; the median is reported.
//! - `--ladder`: instead of the fixed networks, run every measure over a
//!   geometric size ladder (n = 1k to 256k at average degree 10, and n = 2k
//!   with density 0.5% to 40%), fit log-log slopes of time and peak heap
//!   against n and m, and flag measures whose slope exceeds the expected
//!   one. All-pairs measures stop at n = 16k on the sparse ladder.
//! - `--phases`: record the phases of instrumented measures (see
//!   `knappnet::parallel::probe`).
//! - `--csv path`: write one machine-readable row per measurement.
//! - `--summary path`: write a Markdown summary of the largest costs and
//!   the anomalies found.
//!
//! Each line gives the median wall time for each thread count, the process
//! CPU time for the first count (`cpu=`, Linux only, steadier than wall
//! time on a loaded machine), the peak extra heap during one call and the
//! number of allocations it made, and a 64-bit fingerprint of the result
//! bits. Two builds that print the same fingerprint computed bit-identical
//! results. Heap figures come from a counting wrapper around the system
//! allocator, installed only in this example; peak resident memory comes
//! from `VmHWM` in `/proc/self/status` (Linux), reset before each measure
//! where the kernel allows it.
//!
//! The fixed networks are generated by `knappnet::generate` with fixed
//! seeds:
//!
//! | Name | Class | Nodes | Edges | Kind |
//! |---|---|---|---|---|
//! | `sparse10k` | sparse | 10 000 | 50 000 | G(n, m), undirected |
//! | `dir10k` | sparse | 10 000 | 50 000 | G(n, m), directed |
//! | `medium3k` | medium | 3 000 | 89 970 | G(n, m), undirected, density 2% |
//! | `meddir3k` | medium | 3 000 | 179 940 | G(n, m), directed, density 2% |
//! | `dense2k` | dense | 2 000 | 200 000 | G(n, m), undirected, density 10% |
//! | `dense1k` | dense | 1 000 | 149 850 | G(n, m), undirected, density 30% |
//! | `densedir1k` | dense | 1 000 | 299 700 | G(n, m), directed, density 30% |
//! | `sparse100k` | sparse | 100 000 | 500 000 | G(n, m), undirected |
//! | `pa100k` | sparse | 100 000 | 499 990 | preferential attachment, m = 5 |
//!
//! Weighted variants carry integer weights 1..8 (`dial`) or real weights in
//! (0.5, 4) (`dijkstra`). All-pairs measures run on networks of at most
//! 10 000 nodes; linear-time measures run on every network.

